const {PGlite}=require('@electric-sql/pglite');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const db=new PGlite();
  await db.exec('create role anon; create role authenticated;');
  await db.exec(fs.readFileSync('supabase/jenga.sql','utf8'));
  await db.exec('set role anon;');
  const host='host-'.repeat(12),guest='guest-'.repeat(12),outsider='other-'.repeat(12);
  async function rpc(action,token,code='',expected=-1,payload={},name='Alias'){
    return (await db.query('select public.jenga_room($1,$2,$3,$4,$5,$6::jsonb) as state',[action,code,token,name,expected,JSON.stringify(payload)])).rows[0].state;
  }
  let room=await rpc('create',host,'',-1,{},'Ana');
  assert.equal(room.players.length,1);
  const code=room.code;
  assert.equal((await rpc('create',host,'',-1,{},'Ana')).code,code);
  await assert.rejects(()=>db.query('select * from public.jenga_rooms'),/permission denied/);
  await assert.rejects(()=>db.query('select * from public.jenga_players'),/permission denied/);
  await assert.rejects(()=>rpc('sync',outsider,code),/No perteneces/);
  await assert.rejects(()=>rpc('start',host,code,room.revision),/al menos dos/);
  room=await rpc('join',guest,code,-1,{},'Luis');
  await assert.rejects(()=>rpc('start',guest,code,room.revision),/facilitador/);
  room=await rpc('start',host,code,room.revision);
  await assert.rejects(()=>rpc('join',outsider,code,-1,{},'Otro'),/ya comenzó/);
  await assert.rejects(()=>rpc('draw',guest,code,room.revision),/Espera tu turno/);
  await assert.rejects(()=>rpc('draw',host,code,room.revision,{blockId:54}),/no se puede/);
  const sameRevision=room.revision;
  await assert.rejects(()=>rpc('draw',host,code,null,{blockId:5}),/La sala cambió/);
  const attempts=await Promise.allSettled([rpc('draw',host,code,sameRevision,{blockId:23}),rpc('draw',host,code,sameRevision,{blockId:5})]);
  assert.equal(attempts.filter(x=>x.status==='fulfilled').length,1);
  room=await rpc('sync',host,code);
  assert.equal(room.selectedId,23);
  await assert.rejects(()=>rpc('draw',host,code,room.revision,{blockId:5}),/Ya hay una pieza/);
  await assert.rejects(()=>rpc('reveal',host,code,room.revision),/Primero confirma/);
  await assert.rejects(()=>rpc('complete',host,code,room.revision),/Debes responder/);
  room=await rpc('answer',host,code,room.revision);
  room=await rpc('reveal',host,code,room.revision);assert(room.revealed);
  const previousRevision=room.revision;
  room=await rpc('complete',host,code,previousRevision);
  assert.deepEqual(room.moves,[23]);assert.equal(room.turn,1);
  assert.equal(room.activeId,room.players[1].id);
  await assert.rejects(()=>rpc('complete',host,code,previousRevision),/La sala cambió/);
  await assert.rejects(()=>rpc('reset',guest,code,room.revision),/facilitador/);
  room=await rpc('draw',guest,code,room.revision,{blockId:5});
  room=await rpc('answer',guest,code,room.revision);
  room=await rpc('complete',guest,code,room.revision);
  assert.equal(room.activeId,room.players[0].id);assert.deepEqual(room.moves,[23,5]);
  await assert.rejects(()=>rpc('end',guest,code,room.revision),/facilitador/);
  room=await rpc('end',host,code,room.revision);assert.equal(room.status,'ended');
  await assert.rejects(()=>rpc('draw',host,code,room.revision,{blockId:7}),/no está en curso/);
  room=await rpc('reset',host,code,room.revision);assert.equal(room.status,'lobby');assert.deepEqual(room.moves,[]);
  assert(!JSON.stringify(room).includes('token_hash'));assert(!JSON.stringify(room).includes(host));
  await db.exec('reset role;');
  await db.exec("update public.jenga_rooms set expires_at=now()-interval '1 hour';");
  await db.exec('set role anon;');
  await assert.rejects(()=>rpc('sync',host,code),/venció/);
  await db.close();
  console.log('OK PostgreSQL: permisos anon, tokens privados, turnos, respuesta obligatoria, pieza bloqueada, doble solicitud, vuelta de ronda, reinicio y vencimiento.');
})().catch(e=>{console.error(e);process.exitCode=1;});
